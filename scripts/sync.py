#!/usr/bin/env python3
"""Copy the shared sources in core/ into every skill that needs them.

In chat on the web and on phones only a skill's own folder reaches the
sandbox, so each skill carries its own copy of the rules, the country packs,
the scripts and the templates it uses, under skills/<skill>/shared/. The
sources live in core/; core/vendor.json says which skill gets what.

  python scripts/sync.py           write the copies
  python scripts/sync.py --check   exit 1 if any copy is missing or stale
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CORE = REPO / "core"
MANIFEST = CORE / "vendor.json"
GEN = "GENERATED by scripts/sync.py from {src}. Edit the source in core/, then run: python scripts/sync.py"


def demote(md: str) -> str:
    out, fenced = [], False
    for line in md.splitlines():
        if line.lstrip().startswith("```"):
            fenced = not fenced
        if not fenced and re.match(r"^#{1,5} ", line):
            line = "#" + line
        out.append(line)
    return "\n".join(out)


def rules_bundle(manifest: dict) -> str:
    parts, toc = [], []
    for i, name in enumerate(manifest["rules_order"], 1):
        text = (CORE / "rules" / f"{name}.md").read_text(encoding="utf-8").strip()
        title = text.splitlines()[0].lstrip("# ").strip()
        toc.append(f"{i}. {title}")
        parts.append(demote(text))
    head = (f"<!-- {GEN.format(src='core/rules/*.md')} -->\n\n# {manifest['rules_title']}\n\n"
            "These rules apply to every skill and agent. A skill's own SKILL.md carries the\n"
            "short form of the rules it depends on; this file is the full text. Read the\n"
            "section a step points to.\n\n## Contents\n\n" + "\n".join(toc) + "\n")
    return head + "\n---\n\n" + "\n\n---\n\n".join(parts) + "\n"


def stamped(src_rel: str, text: str) -> str:
    note = GEN.format(src=f"core/{src_rel}")
    if src_rel.endswith(".md"):
        return f"<!-- {note} -->\n" + text
    if src_rel.endswith(".py"):
        lines = text.splitlines(keepends=True)
        if lines and lines[0].startswith("#!"):
            return lines[0] + f"# {note}\n" + "".join(lines[1:])
        return f"# {note}\n" + text
    return text  # JSON and other data: byte-identical copy


def expected_files(manifest: dict) -> dict[Path, str]:
    """Map every generated path to its expected content."""
    plugin = REPO / manifest["plugin"]
    files: dict[Path, str] = {}
    bundle = rules_bundle(manifest)
    for skill, wanted in manifest["skills"].items():
        sdir = plugin / "skills" / skill
        for key in wanted:
            spec = manifest["bundles"][key]
            if "bundle_to" in spec:
                files[sdir / spec["bundle_to"]] = bundle
            if "glob" in spec:
                for src in sorted(CORE.glob(spec["glob"])):
                    rel = src.relative_to(CORE).as_posix()
                    files[sdir / spec["to_dir"] / src.name] = stamped(rel, src.read_text(encoding="utf-8"))
            for src_rel, dst_rel in spec.get("files", {}).items():
                text = (CORE / src_rel).read_text(encoding="utf-8")
                files[sdir / dst_rel] = stamped(src_rel, text)
    for src_rel, dst_rel in manifest.get("plugin_copies", {}).items():
        files[plugin / dst_rel] = (REPO / src_rel).read_text(encoding="utf-8")
    return files


def generated_on_disk(manifest: dict) -> set[Path]:
    plugin = REPO / manifest["plugin"]
    return {p for p in (plugin / "skills").glob("*/shared/**/*") if p.is_file()}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    want = expected_files(manifest)
    stale = []
    for path, content in want.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    extra = sorted(generated_on_disk(manifest) - set(want))
    if not args.check:
        for p in extra:
            p.unlink()
    rel = lambda p: p.relative_to(REPO).as_posix()  # noqa: E731
    report = {"ok": not (args.check and (stale or extra)),
              "mode": "check" if args.check else "write",
              "files": len(want), "stale": [rel(p) for p in stale], "removed_or_extra": [rel(p) for p in extra]}
    print(json.dumps(report, indent=2))
    return 0 if report["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
